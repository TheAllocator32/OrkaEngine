/*
 * Shader file formats
 * Since Orka internally uses bgfx, it also uses the bgfx binary shader format! To simplify file loading across different APIs, Orka uses .*API*.shader
 * API          Extension
 * Vulkan       .vk.shader
 * DirectX11    .dx11.shader
 * DirectX12    .dx12.shader
 * OpenGL3/4    .gln.shader
 * OpenGL 1/2    .glo.shader
 * OpenGLES        .gles.shader
 * WebGL        .web.shader
 * Metal        .mt.shader
 */

using ShaderUniformType = std::variant<float, int, long, /*vector3d*/ vector3di, vector3df, vector3dd, /*vector2d*/ vector2di, vector2df, vector2dd, /*vector4d*/ vector4di, vector4df, vector4dd, /*matrix*/ matrix4x4f, matrix4x3f, matrix4x4d, matrix4x3d>;

enum ShaderSourceMode {
    SSM_NONE,
    SSM_FILE,
    SSM_BUFFER,
    SSM_STRING
};

enum ShaderFileLayout {
    SFL_AUTO,            // Prefer .vert/.frag backend-specific files if both exist, fallback to single .<backend>.shader
    SFL_SINGLE_FILE,    // Force single .<backend>.shader
    SFL_STAGE_FILES        // Force split .vert.<backend>.shader + .frag.<backend>.shader
};

struct ShaderBufferView {
    const uint8_t* data = nullptr;
    uint32_t size = 0;

    constexpr ShaderBufferView() = default;
    constexpr ShaderBufferView(const uint8_t* p_data, uint32_t p_size) : data(p_data), size(p_size) {}

    inline constexpr bool empty() const {
        return data == nullptr || size == 0;
    }
};

struct ShaderStageSource {
    ShaderSourceMode mode = SSM_NONE;
    std::string text; // File path if mode == SSM_FILE, shader code if mode == SSM_STRING
    ShaderBufferView buffer;

    static inline ShaderStageSource file(std::string_view path) {
        ShaderStageSource s;
        s.mode = SSM_FILE;
        s.text = std::string(path);
        return s;
    }

    static inline ShaderStageSource source(std::string_view code) {
        ShaderStageSource s;
        s.mode = SSM_STRING;
        s.text = std::string(code);
        return s;
    }

    static inline ShaderStageSource binary(ShaderBufferView view) {
        ShaderStageSource s;
        s.mode = SSM_BUFFER;
        s.buffer = view;
        return s;
    }
};

struct Shader {
    template <typename TNamedShader>
    struct AutogeneratedSymbols;

    template <typename TNamedShader>
    inline static constexpr bool hasAutogeneratedSymbols = requires {
        { AutogeneratedSymbols<TNamedShader>::vertGL() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::vertGLLegacy() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::vertGLES() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::vertWEBGL() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::vertVulkan() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::vertDX11() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::vertDX12() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::vertMetal() } -> std::same_as<ShaderBufferView>;

        { AutogeneratedSymbols<TNamedShader>::fragGL() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::fragGLLegacy() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::fragGLES() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::fragWEBGL() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::fragVulkan() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::fragDX11() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::fragDX12() } -> std::same_as<ShaderBufferView>;
        { AutogeneratedSymbols<TNamedShader>::fragMetal() } -> std::same_as<ShaderBufferView>;
    };

    // Set a uniform (stays persistent until you overwrite it)
    void setUniform(std::string_view name, ShaderUniformType value);

    // Empty shader definition
    inline Shader() = default;

    // Attention! You are probably searching for FileLoader::loadShader(path) that automatically handles extensions! This one here does pretty nothing.
    inline Shader(std::string_view path)
        : m_path(path),
          m_vertexSource(ShaderStageSource::file(path)),
          m_fragmentSource(ShaderStageSource::file(path)) {};

    // File mode with explicit stage files.
    inline Shader(std::string_view vertexPath, std::string_view fragmentPath)
        : m_path(fragmentPath),
          m_vertexSource(ShaderStageSource::file(vertexPath)),
          m_fragmentSource(ShaderStageSource::file(fragmentPath)) {}

    // File mode helper: base path + backend-specific extension (+ optional .vert/.frag split)
    static Shader fromFile(std::string_view pathWithoutFileExtension, ShaderFileLayout layout = SFL_AUTO, RenderSystemType renderSystem = RST_AUTO);

    // Buffer mode (compiled binaries).
    static Shader fromBuffers(ShaderBufferView vertexBuffer, ShaderBufferView fragmentBuffer);

    // String/source mode (raw shader code).
    static Shader fromStrings(std::string_view vertexCode, std::string_view fragmentCode);

    // Template entry point for autogenerated shader headers.
    // Usage:
    //   #include "unlit.autogenerated.shader.hpp"
    //   ORKA_SHADER_DECLARE_AUTOGENERATED(unlit)
    //   Shader shader = Shader::fromAutogenerated<unlit>();
    template <typename TNamedShader>
    inline static Shader fromAutogenerated(RenderSystemType renderSystem = RST_AUTO) {
        static_assert(hasAutogeneratedSymbols<TNamedShader>,
            "Missing autogenerated shader symbol mapping. Use ORKA_SHADER_DECLARE_AUTOGENERATED(name) after including the *.autogenerated.shader.hpp file.");

        const RenderSystemType resolvedRenderSystem = resolveRenderSystem(renderSystem);
        const ShaderBufferView vertex = selectBufferForRenderSystem(
            resolvedRenderSystem,
            AutogeneratedSymbols<TNamedShader>::vertGL(),
            AutogeneratedSymbols<TNamedShader>::vertGLLegacy(),
            AutogeneratedSymbols<TNamedShader>::vertGLES(),
            AutogeneratedSymbols<TNamedShader>::vertWEBGL(),
            AutogeneratedSymbols<TNamedShader>::vertVulkan(),
            AutogeneratedSymbols<TNamedShader>::vertDX11(),
            AutogeneratedSymbols<TNamedShader>::vertDX12(),
            AutogeneratedSymbols<TNamedShader>::vertMetal()
        );
        const ShaderBufferView fragment = selectBufferForRenderSystem(
            resolvedRenderSystem,
            AutogeneratedSymbols<TNamedShader>::fragGL(),
            AutogeneratedSymbols<TNamedShader>::fragGLLegacy(),
            AutogeneratedSymbols<TNamedShader>::fragGLES(),
            AutogeneratedSymbols<TNamedShader>::fragWEBGL(),
            AutogeneratedSymbols<TNamedShader>::fragVulkan(),
            AutogeneratedSymbols<TNamedShader>::fragDX11(),
            AutogeneratedSymbols<TNamedShader>::fragDX12(),
            AutogeneratedSymbols<TNamedShader>::fragMetal()
        );

        if (vertex.empty() || fragment.empty()) {
            Logger::log(LET_WARN, "Orka, Shader", "Autogenerated shader backend selection resulted in an empty stage buffer. Check compiled backends.");
        }

        return fromBuffers(vertex, fragment);
    }

    static void setActiveRenderSystem(RenderSystemType renderSystem) { sm_activeRenderSystem = renderSystem; }

    inline static RenderSystemType getActiveRenderSystem() { return sm_activeRenderSystem; }

    static RenderSystemType resolveRenderSystem(RenderSystemType requestedRenderSystem = RST_AUTO);

    static std::string getFileBackendSuffix(RenderSystemType renderSystem);

    static std::string getGeneratedBackendSuffix(RenderSystemType renderSystem);

    static ShaderBufferView selectBufferForRenderSystem(RenderSystemType renderSystem, ShaderBufferView gl, ShaderBufferView glLegacy, ShaderBufferView gles, ShaderBufferView webgl, ShaderBufferView vulkan, ShaderBufferView dx11, ShaderBufferView dx12, ShaderBufferView metal);

    // Returns all uniforms (you shouldn't need this! Thought for Rendering...)
    inline std::vector<std::pair<std::string, ShaderUniformType>>& getUniforms() { return m_uniforms; }
    inline const std::vector<std::pair<std::string, ShaderUniformType>>& getUniforms() const { return m_uniforms; }
    // Returns the FilePath (with extension)
    inline std::string getPath() { return m_path; }
    inline std::string getPath() const { return m_path; }

    // Stage source inspection helpers
    inline const ShaderStageSource& getVertexSource() const { return m_vertexSource; }
    inline const ShaderStageSource& getFragmentSource() const { return m_fragmentSource; }

    inline ShaderSourceMode getVertexSourceMode() const { return m_vertexSource.mode; }
    inline ShaderSourceMode getFragmentSourceMode() const { return m_fragmentSource.mode; }

    inline bool usesSplitStageFiles() const {
        return m_vertexSource.mode == SSM_FILE &&
            m_fragmentSource.mode == SSM_FILE &&
            !m_vertexSource.text.empty() &&
            !m_fragmentSource.text.empty() &&
            m_vertexSource.text != m_fragmentSource.text;
    }

    inline std::string getVertexPath() const { return m_vertexSource.mode == SSM_FILE ? m_vertexSource.text : ""; }
    inline std::string getFragmentPath() const { return m_fragmentSource.mode == SSM_FILE ? m_fragmentSource.text : ""; }
    inline ShaderBufferView getVertexBuffer() const { return m_vertexSource.mode == SSM_BUFFER ? m_vertexSource.buffer : ShaderBufferView(); }
    inline ShaderBufferView getFragmentBuffer() const { return m_fragmentSource.mode == SSM_BUFFER ? m_fragmentSource.buffer : ShaderBufferView(); }
    inline std::string getVertexCode() const { return m_vertexSource.mode == SSM_STRING ? m_vertexSource.text : ""; }
    inline std::string getFragmentCode() const { return m_fragmentSource.mode == SSM_STRING ? m_fragmentSource.text : ""; }

private:
    static bool fileExists(std::string_view path);
    static RenderSystemType getConfiguredRenderSystem();

    std::vector<std::pair<std::string, ShaderUniformType>> m_uniforms; // Faster iteration -> vector
    std::string m_path;
    ShaderStageSource m_vertexSource;
    ShaderStageSource m_fragmentSource;
    inline static RenderSystemType sm_activeRenderSystem = RST_AUTO;
};

